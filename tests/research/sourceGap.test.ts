import { describe, expect, it } from 'vitest';

import { compareSheetAndAuto } from '@/lib/research/merge/sheetAuto';
import type { ResearchDossier } from '@/lib/research/types';

/**
 * The XOS incident, as a contract.
 *
 * Xos announced a US Air Force contract through GlobeNewswire at 16:30 ET on
 * 17 August. The automatic bundle ran at 17:00 and contained eight SEC-derived
 * sources ending on 13 August. The release was never collected, so the analysis
 * reported a stale secondary catalyst — accurately, from what it was given.
 *
 * Two things then went wrong that were nobody's judgement call:
 *
 *   1. Coverage said `incomplete: false`. An 8-K exhibit is a catalyst source
 *      AND an SEC document, so an SEC-only bundle satisfied "a catalyst source
 *      was located" and declared itself gap-free.
 *   2. The merge called the resulting disagreement INTERPRETATION_DIFFERENCE —
 *      "both sides had evidence and reached different judgements" — when in
 *      fact only one side had been shown the news.
 *
 * These fix the second. The first is covered in interpret.test.ts, where an
 * SEC-only bundle now reports incomplete coverage.
 */

function dossier(overrides: Partial<ResearchDossier> = {}): ResearchDossier {
  return {
    schemaVersion: 1,
    ticker: 'XOS',
    catalyst: {
      catalystGrade: 'MODERATE_MIXED_SECONDARY',
      catalystType: 'OTHER',
      catalystSummary: 'Latest company event on file is the 13 August quarterly result.',
      evidenceSourceIds: [1],
      confidence: 'MEDIUM',
    },
    structure: {
      structureClassification: 'CAUTION',
      structureSummary: 'Shelf on file.',
      evidenceSourceIds: [1],
      confidence: 'MEDIUM',
    },
    cycle: {
      cycleClassification: 'UNKNOWN',
      cycleSummary: 'No determination.',
      evidenceSourceIds: [],
      confidence: 'LOW',
    },
    unknowns: ['No company announcement dated 17 August was supplied.'],
    ...overrides,
  } as unknown as ResearchDossier;
}

/**
 * The sheet as the desk actually records it: coarse buckets and states, not
 * display strings. Comparison happens at family level, which is the honest
 * resolution — a grade difference inside one bucket is not a conflict.
 */
const SHEET = {
  catalyst: { gradeBucket: 'A', latestTime: '2026-08-17; exact time Unknown' },
  structure: { state: 'UNKNOWN_STRUCTURE', raw: 'UNKNOWN STRUCTURE', floatRaw: '', badges: [] },
  cycle: { state: 'FRESH_FRONTSIDE', raw: 'GREEN — FRESH / FRONTSIDE', display: 'FRESH / FRONTSIDE' },
  observedAt: '2026-08-17T21:00:00Z',
} as unknown as Parameters<typeof compareSheetAndAuto>[0]['sheet'] & { observedAt: string };

describe('a disagreement caused by different evidence', () => {
  it('is reported as a source gap, not a difference of judgement', () => {
    const result = compareSheetAndAuto({
      ticker: 'XOS',
      sheet: SHEET,
      auto: dossier(),
      autoGeneratedAt: '2026-08-17T21:00:24Z',
      // Coverage looked complete at the time. That was the other half of the
      // bug; the classification must be right even when it does not.
      autoCoverageIncomplete: false,
      // The newest source the analysis held: 13 August. The sheet was observed
      // on the 17th, after an announcement the analysis never received.
      autoLatestSourceAt: '2026-08-13T20:00:00Z',
    });

    const catalyst = result.comparisons.find((entry) => entry.field === 'catalyst');
    expect(catalyst?.agreement).toBe('DISAGREE');
    expect(catalyst?.reason).toBe('AUTO_SOURCE_GAP');
    // The detail is what a trader reads. It must not claim both sides weighed
    // the same evidence.
    expect(catalyst?.detail).toContain('different evidence');
    expect(catalyst?.detail).not.toContain('reached different judgements');
  });

  it('still reports a genuine judgement dispute as an interpretation difference', () => {
    // Same event, different grade: the sheet was observed BEFORE the newest
    // source, so nothing is missing from the automatic side.
    const result = compareSheetAndAuto({
      ticker: 'XOS',
      sheet: { ...SHEET, catalyst: { gradeBucket: 'B', latestTime: '2026-08-13; exact time Unknown' } as unknown as NonNullable<typeof SHEET>['catalyst'], observedAt: '2026-08-13T12:00:00Z' },
      auto: dossier({
        catalyst: {
          catalystGrade: 'STRONG',
          catalystType: 'CONTRACT',
          catalystSummary: 'Contract award.',
          evidenceSourceIds: [1],
          confidence: 'HIGH',
        },
      } as unknown as Partial<ResearchDossier>),
      autoGeneratedAt: '2026-08-17T21:00:24Z',
      autoCoverageIncomplete: false,
      autoLatestSourceAt: '2026-08-17T20:30:00Z',
    });

    const catalyst = result.comparisons.find((entry) => entry.field === 'catalyst');
    expect(catalyst?.reason).not.toBe('AUTO_SOURCE_GAP');
  });

  it('leaves structural disputes alone, even when the sheet is newer', () => {
    /*
     * SGLY's DIRTY_FLOAT against CAUTION is a product-definition dispute about
     * the same financing evidence, and it must keep escalating. Structure rests
     * on registration filings, not on announcements, so "the sheet was observed
     * after the newest source" says nothing about whether the two sides read
     * the same thing — and escalation only fires on INTERPRETATION_DIFFERENCE.
     */
    const result = compareSheetAndAuto({
      ticker: 'SGLY',
      sheet: { ...SHEET, structure: { state: 'DIRTY_FLOAT', raw: 'DIRTY FLOAT', floatRaw: '', badges: [] }, observedAt: '2026-08-17T21:00:00Z' },
      auto: dossier(),
      autoGeneratedAt: '2026-08-17T21:00:24Z',
      autoCoverageIncomplete: false,
      autoLatestSourceAt: '2026-08-13T20:00:00Z',
    });

    const structure = result.comparisons.find((entry) => entry.field === 'structure');
    expect(structure?.agreement).toBe('DISAGREE');
    expect(structure?.reason).toBe('INTERPRETATION_DIFFERENCE');
  });

  it('does not invent a gap when the analysis holds the newer evidence', () => {
    // The mirror case, which already had a name: AUTO_NEW_EVIDENCE.
    const result = compareSheetAndAuto({
      ticker: 'XOS',
      sheet: {
        ...SHEET,
        catalyst: { gradeBucket: 'A', latestTime: '2026-08-10; exact time Unknown' } as unknown as NonNullable<typeof SHEET>['catalyst'],
        observedAt: '2026-08-10T12:00:00Z',
      },
      auto: dossier(),
      autoGeneratedAt: '2026-08-17T21:00:24Z',
      autoCoverageIncomplete: false,
      autoLatestSourceAt: '2026-08-17T20:30:00Z',
    });

    const catalyst = result.comparisons.find((entry) => entry.field === 'catalyst');
    expect(catalyst?.reason).toBe('AUTO_NEW_EVIDENCE');
  });

  it('says nothing about evidence when the two sides agree', () => {
    const result = compareSheetAndAuto({
      ticker: 'XOS',
      sheet: { ...SHEET, structure: { state: 'CLEAN', raw: 'CLEAN', floatRaw: '', badges: [] } },
      auto: dossier({
        structure: {
          structureClassification: 'CLEAN',
          structureSummary: 'No live shelf.',
          evidenceSourceIds: [1],
          confidence: 'HIGH',
        },
      } as unknown as Partial<ResearchDossier>),
      autoGeneratedAt: '2026-08-17T21:00:24Z',
      autoCoverageIncomplete: false,
      autoLatestSourceAt: '2026-08-13T20:00:00Z',
    });

    const structure = result.comparisons.find((entry) => entry.field === 'structure');
    expect(structure?.agreement).toBe('AGREE');
    expect(structure?.reason).toBeNull();
  });
  it('makes no claim when both sides land on the same day and one has no time', () => {
    /*
     * The sheet records "exact time Unknown" constantly. If the automatic
     * evidence is from the same calendar day, there is genuinely no way to know
     * which came first — and inventing an order would turn "we cannot tell"
     * into "the analysis missed something", which is an accusation the data
     * does not support.
     */
    const result = compareSheetAndAuto({
      ticker: 'XOS',
      sheet: SHEET,
      auto: dossier(),
      autoGeneratedAt: '2026-08-17T21:00:24Z',
      autoCoverageIncomplete: false,
      autoLatestSourceAt: '2026-08-17T13:00:00Z',
    });

    const catalyst = result.comparisons.find((entry) => entry.field === 'catalyst');
    expect(catalyst?.reason).not.toBe('AUTO_SOURCE_GAP');
  });

  it('is not fooled by a newer filing that the catalyst does not rest on', () => {
    /*
     * The caller passes the newest CATALYST evidence, not the newest source.
     * A registration statement filed this morning says nothing about whether
     * yesterday's announcement was seen, and letting it stand in would hide
     * exactly the staleness this check exists to find.
     */
    const result = compareSheetAndAuto({
      ticker: 'XOS',
      sheet: SHEET,
      auto: dossier(),
      autoGeneratedAt: '2026-08-18T09:00:00Z',
      autoCoverageIncomplete: false,
      // Catalyst evidence is still the 13th, even though an S-3 landed later.
      autoLatestSourceAt: '2026-08-13T20:00:00Z',
    });

    const catalyst = result.comparisons.find((entry) => entry.field === 'catalyst');
    expect(catalyst?.reason).toBe('AUTO_SOURCE_GAP');
  });
});
