/**
 * Sheet / AUTO reconciliation.
 *
 * The Google Sheet is the desk's human-reviewed research and is never written
 * to, never overwritten and never silently superseded. Automatic analysis is a
 * second, independent opinion. Where they agree that is worth knowing; where
 * they disagree the disagreement is the finding, and both conclusions stay
 * visible so a person can adjudicate.
 *
 * Nothing here assumes AUTO is correct.
 */

import type { CycleField, CatalystField, StructureField } from '../../data/types';
import type { ResearchDossier } from '../types';

export type MergeProvenance =
  | 'SHEET'
  | 'AUTO'
  | 'SHEET_AUTO_AGREE'
  | 'CONFLICT'
  | 'AUTO_NEWER'
  | 'SHEET_NEWER'
  | 'NONE';

/**
 * Why two conclusions differ.
 *
 * The reason must name the side that actually lacks evidence. Labelling
 * "the sheet says unknown, the automatic layer says DIRTY_FLOAT on complete
 * coverage" as AUTO_INCOMPLETE inverts the finding: it blames the side that
 * did the work, and would hide a real discovery behind an apology.
 */
export type ConflictReason =
  | 'SOURCE_DIFFERENCE'
  | 'TIMING_DIFFERENCE'
  | 'INTERPRETATION_DIFFERENCE'
  | 'SHEET_STALE'
  | 'SHEET_INCOMPLETE'
  | 'AUTO_INCOMPLETE'
  | 'AUTO_NEW_EVIDENCE'
  | 'POTENTIAL_SHEET_ERROR'
  | 'UNKNOWN';

export type FieldAgreement = 'AGREE' | 'DISAGREE' | 'SHEET_ONLY' | 'AUTO_ONLY' | 'NEITHER';

export interface FieldComparison {
  field: 'catalyst' | 'structure' | 'cycle';
  sheet: string | null;
  auto: string | null;
  agreement: FieldAgreement;
  reason: ConflictReason | null;
  detail: string;
}

export interface SheetAutoComparison {
  ticker: string;
  provenance: MergeProvenance;
  comparisons: FieldComparison[];
  /** True when any field materially disagrees. */
  conflict: boolean;
  conflictReasons: ConflictReason[];
  autoGeneratedAt: string | null;
  sheetObservedAt: string | null;
}

/** Maps the sheet's cycle vocabulary onto the automatic classification. */
function sheetCycleToAuto(state: CycleField['state'] | undefined): string | null {
  switch (state) {
    case 'FRESH_FRONTSIDE':
      return 'GREEN_FRESH_FRONTSIDE';
    case 'FRONTSIDE_WARNING':
      return 'YELLOW_FRONTSIDE_WARNING';
    case 'BACKSIDE':
      return 'RED_BACKSIDE';
    default:
      return null;
  }
}

/** Maps the sheet's structure vocabulary onto the automatic classification. */
function sheetStructureToAuto(state: StructureField['state'] | undefined): string | null {
  switch (state) {
    case 'DIRTY_FLOAT':
      return 'DIRTY_FLOAT';
    case 'CLEAN':
      return 'CLEAN';
    case 'UNKNOWN_STRUCTURE':
      return 'UNKNOWN';
    default:
      // UNCLASSIFIED means the sheet did not say, which is not a conclusion.
      return null;
  }
}

/**
 * Maps the sheet's coarse catalyst bucket onto the automatic grade families.
 *
 * The sheet records A/B/C buckets; the automatic grades are finer. Comparison
 * is therefore at family level, which is the honest resolution — treating a
 * grade difference within one bucket as a conflict would manufacture noise.
 */
function catalystFamily(grade: string | null): string | null {
  switch (grade) {
    case 'STRONG':
    case 'LEGITIMATE_POSITIVE':
      return 'POSITIVE';
    case 'MODERATE_MIXED_SECONDARY':
      return 'MIXED';
    case 'WEAK_NEGATIVE_DILUTIVE':
      return 'NEGATIVE';
    case 'NONE':
      return 'NONE';
    default:
      return null;
  }
}

function sheetCatalystFamily(bucket: CatalystField['gradeBucket'] | undefined): string | null {
  switch (bucket) {
    case 'A':
      return 'POSITIVE';
    case 'B':
      return 'MIXED';
    case 'C':
      return 'NEGATIVE';
    default:
      return null;
  }
}

interface CompareContext {
  /** The automatic side reached no conclusion for this field. */
  autoUnknown: boolean;
  /** Deterministic collection recorded gaps. */
  autoIncomplete: boolean;
  /** The sheet's own value is an explicit "unknown", not a conclusion. */
  sheetUnknown: boolean;
  /** Automatic evidence postdates the human review. */
  sheetStale: boolean;
}

/** Sheet values that state "we do not know" rather than a conclusion. */
const SHEET_UNKNOWN_VALUES = new Set(['UNKNOWN']);

function compare(
  field: FieldComparison['field'],
  sheet: string | null,
  auto: string | null,
  context: CompareContext,
): FieldComparison {
  if (sheet === null && auto === null) {
    return { field, sheet, auto, agreement: 'NEITHER', reason: null, detail: 'neither source states a conclusion' };
  }
  if (sheet === null) {
    return { field, sheet, auto, agreement: 'AUTO_ONLY', reason: null, detail: 'no human conclusion on file' };
  }
  if (auto === null) {
    return { field, sheet, auto, agreement: 'SHEET_ONLY', reason: null, detail: 'automatic analysis reached no conclusion' };
  }
  if (sheet === auto) {
    return { field, sheet, auto, agreement: 'AGREE', reason: null, detail: 'conclusions match' };
  }

  /*
   * Order matters. The first question is which side is short of evidence, and
   * only then whose judgement differs. Blaming the automatic layer whenever it
   * disagrees would bury exactly the cases worth reading.
   */
  let reason: ConflictReason;
  let detail: string;

  if (context.autoIncomplete || context.autoUnknown) {
    reason = 'AUTO_INCOMPLETE';
    detail = 'automatic coverage is incomplete, so its conclusion is the weaker one';
  } else if (context.sheetUnknown) {
    // The sheet says it does not know; the automatic layer, on complete
    // coverage, does. That is a gap on the human side, not an automatic error.
    reason = 'SHEET_INCOMPLETE';
    detail = 'the human review recorded no determination while automatic coverage was adequate';
  } else if (context.sheetStale) {
    reason = 'AUTO_NEW_EVIDENCE';
    detail = 'automatic analysis rests on public evidence published after the human review';
  } else {
    reason = 'INTERPRETATION_DIFFERENCE';
    detail = 'both sides had evidence and reached different judgements';
  }

  return { field, sheet, auto, agreement: 'DISAGREE', reason, detail };
}

export interface SheetSnapshot {
  cycle?: CycleField;
  catalyst?: CatalystField;
  structure?: StructureField;
  /** When the sheet row was last observed, if known. */
  observedAt?: string | null;
}

export interface CompareOptions {
  ticker: string;
  sheet: SheetSnapshot | null;
  auto: ResearchDossier | null;
  autoGeneratedAt: string | null;
  autoCoverageIncomplete: boolean;
  /**
   * Publication date of the newest source the automatic analysis used.
   *
   * Staleness has to be judged against when the EVIDENCE was published, not
   * when the analysis ran. Comparing against the run time made every human
   * review look stale — the automatic layer always runs later — which
   * mislabelled genuine judgement disputes as "newer evidence".
   */
  autoLatestSourceAt?: string | null;
}

export function compareSheetAndAuto(options: CompareOptions): SheetAutoComparison {
  const { ticker, sheet, auto } = options;

  if (!sheet && !auto) {
    return {
      ticker,
      provenance: 'NONE',
      comparisons: [],
      conflict: false,
      conflictReasons: [],
      autoGeneratedAt: null,
      sheetObservedAt: null,
    };
  }

  if (!auto) {
    return {
      ticker,
      provenance: 'SHEET',
      comparisons: [],
      conflict: false,
      conflictReasons: [],
      autoGeneratedAt: null,
      sheetObservedAt: sheet?.observedAt ?? null,
    };
  }

  if (!sheet) {
    return {
      ticker,
      provenance: 'AUTO',
      comparisons: [],
      conflict: false,
      conflictReasons: [],
      autoGeneratedAt: options.autoGeneratedAt,
      sheetObservedAt: null,
    };
  }

  // Stale means the issuer published something after the human looked, not
  // merely that our analysis ran afterwards.
  const sheetStale = Boolean(
    sheet.observedAt &&
      options.autoLatestSourceAt &&
      Date.parse(options.autoLatestSourceAt) > Date.parse(sheet.observedAt),
  );

  const base = {
    autoUnknown: false,
    autoIncomplete: options.autoCoverageIncomplete,
    sheetUnknown: false,
    sheetStale,
  };

  const sheetStructure = sheetStructureToAuto(sheet.structure?.state);
  const sheetCycle = sheetCycleToAuto(sheet.cycle?.state);
  const sheetCatalyst = sheetCatalystFamily(sheet.catalyst?.gradeBucket);

  const comparisons: FieldComparison[] = [
    compare('catalyst', sheetCatalyst, catalystFamily(auto.catalyst.catalystGrade), {
      ...base,
      autoUnknown: auto.catalyst.catalystGrade === 'UNKNOWN',
      sheetUnknown: sheetCatalyst !== null && SHEET_UNKNOWN_VALUES.has(sheetCatalyst),
    }),
    compare(
      'structure',
      sheetStructure,
      auto.structure.structureClassification === 'UNKNOWN'
        ? null
        : auto.structure.structureClassification,
      {
        ...base,
        autoUnknown: auto.structure.structureClassification === 'UNKNOWN',
        sheetUnknown: sheetStructure !== null && SHEET_UNKNOWN_VALUES.has(sheetStructure),
      },
    ),
    compare(
      'cycle',
      sheetCycle,
      auto.cycle.cycleClassification === 'UNKNOWN' ? null : auto.cycle.cycleClassification,
      {
        ...base,
        autoUnknown: auto.cycle.cycleClassification === 'UNKNOWN',
        sheetUnknown: sheetCycle !== null && SHEET_UNKNOWN_VALUES.has(sheetCycle),
      },
    ),
  ];

  const disagreements = comparisons.filter((item) => item.agreement === 'DISAGREE');
  const agreements = comparisons.filter((item) => item.agreement === 'AGREE');

  let provenance: MergeProvenance;
  if (disagreements.length > 0) provenance = 'CONFLICT';
  else if (agreements.length > 0) provenance = 'SHEET_AUTO_AGREE';
  else if (sheetStale) provenance = 'AUTO_NEWER';
  else provenance = 'SHEET_NEWER';

  return {
    ticker,
    provenance,
    comparisons,
    conflict: disagreements.length > 0,
    conflictReasons: [...new Set(disagreements.map((item) => item.reason ?? 'UNKNOWN'))],
    autoGeneratedAt: options.autoGeneratedAt,
    sheetObservedAt: sheet.observedAt ?? null,
  };
}
