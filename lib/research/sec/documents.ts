/**
 * Filing document handling: HTML to readable text, and bounded extraction.
 *
 * Two constraints shape this module. Legally, we keep source metadata and the
 * limited evidence analysis needs rather than copying whole filings into our
 * database. Practically, sending a full 10-K to a model is both wasteful and
 * worse than sending the paragraphs that actually bear on the question.
 *
 * So: fetch, normalise, extract targeted passages, retain those. The full text
 * is used in-process and discarded.
 */

/** Upper bound on retained evidence per document. */
export const MAX_EXCERPT_CHARS = 4000;
/** Characters of context captured around a matched term. */
const CONTEXT_CHARS = 480;

const BLOCK_TAGS =
  /<\/?(p|div|br|tr|td|th|li|ul|ol|table|h[1-6]|section|article|header|footer)\b[^>]*>/gi;

/**
 * Converts filing HTML to plain text.
 *
 * EDGAR documents are frequently generated by word processors and carry heavy
 * inline styling, so tag stripping is preceded by removing whole elements whose
 * content is never prose.
 */
export function htmlToText(html: string): string {
  let text = html;

  // Elements whose contents are markup, not readable content.
  text = text.replace(/<(script|style|head)\b[^>]*>[\s\S]*?<\/\1>/gi, ' ');
  text = text.replace(/<!--[\s\S]*?-->/g, ' ');

  // Preserve block structure as newlines before dropping the remaining tags.
  text = text.replace(BLOCK_TAGS, '\n');
  text = text.replace(/<[^>]+>/g, ' ');

  text = decodeEntities(text);

  // Collapse the whitespace explosion that inline styling leaves behind.
  text = text.replace(/[ \t ]+/g, ' ');
  text = text.replace(/\s*\n\s*/g, '\n');
  text = text.replace(/\n{3,}/g, '\n\n');

  return text.trim();
}

const NAMED_ENTITIES: Record<string, string> = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
  mdash: '—',
  ndash: '–',
  rsquo: '’',
  lsquo: '‘',
  ldquo: '“',
  rdquo: '”',
};

export function decodeEntities(text: string): string {
  return text
    .replace(/&#x([0-9a-f]+);/gi, (_, hex: string) =>
      String.fromCodePoint(Number.parseInt(hex, 16)),
    )
    .replace(/&#(\d+);/g, (_, dec: string) => String.fromCodePoint(Number(dec)))
    .replace(/&([a-z]+);/gi, (match, name: string) => NAMED_ENTITIES[name.toLowerCase()] ?? match);
}

/**
 * Structural concepts worth extracting, and the language that signals each.
 *
 * Grouping by concept rather than keeping a flat term list is what makes
 * coverage measurable: we can state which structural questions a filing
 * actually spoke to, instead of only how many words matched. This phase
 * collects the passages; it does not interpret them.
 */
