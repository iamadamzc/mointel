export const EXTRACTION_TERMS: readonly string[] = Object.values(EXTRACTION_CONCEPTS).flat();

/** Maximum windows kept per concept, so one concept cannot eat the budget. */
const MAX_WINDOWS_PER_CONCEPT = 2;

export interface EvidenceWindow {
  /** Character offsets into the normalised document text: location provenance. */
  start: number;
  end: number;
  concepts: EvidenceConcept[];
  terms: string[];
  text: string;
}

export interface ExtractedEvidence {
  /** Bounded passages, joined; never the whole document. */
  excerpt: string;
  windows: EvidenceWindow[];
  /** Structural concepts this document actually spoke to. */
  concepts: EvidenceConcept[];
  /** Which terms matched, for provenance in the report. */
  matchedTerms: string[];
  /** Characters in the full document, so reduction is visible. */
  fullLength: number;
  truncated: boolean;
  /**
   * True when no concept matched and the opening was retained instead. Callers
   * must be able to tell a targeted excerpt from a fallback one — a fallback is
   * weaker evidence and should not be presented as if it were targeted.
   */
  fallback: boolean;
}

interface Hit {
  index: number;
  term: string;
  concept: EvidenceConcept;
}

function findHits(haystack: string, concepts: Record<string, readonly string[]>): Hit[] {
  const hits: Hit[] = [];

  for (const [concept, terms] of Object.entries(concepts)) {
    let found = 0;
    for (const term of terms) {
      if (found >= MAX_WINDOWS_PER_CONCEPT) break;
      // Multiple occurrences matter: the first mention of "warrant" is often a
      // heading, while the operative terms appear further down.
      let from = 0;
      while (found < MAX_WINDOWS_PER_CONCEPT) {
        const index = haystack.indexOf(term.toLowerCase(), from);
        if (index === -1) break;
        hits.push({ index, term, concept: concept as EvidenceConcept });
        found += 1;
        from = index + term.length;
      }
    }
  }

  return hits;
}

/**
 * Pulls the passages that bear on structure and financing.
 *
 * Windows are allocated breadth-first across concepts, so a filing that
 * discusses warrants at length cannot crowd out the one sentence stating the
 * share count. Offsets are retained so every retained passage can be located in
 * the source document.
 *
 * When nothing matches, the opening is retained and flagged as a fallback: a
 * filing whose wording we did not anticipate is still evidence, and dropping it
 * silently would be worse than keeping it labelled.
 */
export function extractEvidence(
  text: string,
  concepts: Record<string, readonly string[]> = EXTRACTION_CONCEPTS,
): ExtractedEvidence {
  const haystack = text.toLowerCase();
  const hits = findHits(haystack, concepts);

  if (hits.length === 0) {
    const head = text.slice(0, MAX_EXCERPT_CHARS);
    return {
      excerpt: head,
      windows: [],
      concepts: [],
      matchedTerms: [],
      fullLength: text.length,
      truncated: text.length > head.length,
      fallback: true,
    };
  }

  // Breadth before depth: one window per concept, then a second pass, so the
  // excerpt covers as many structural questions as the budget allows.
  const byConcept = new Map<EvidenceConcept, Hit[]>();
  for (const hit of hits) {
    const bucket = byConcept.get(hit.concept);
    if (bucket) bucket.push(hit);
    else byConcept.set(hit.concept, [hit]);
  }

  const ordered: Hit[] = [];
  for (let round = 0; round < MAX_WINDOWS_PER_CONCEPT; round += 1) {
    for (const bucket of byConcept.values()) {
      if (bucket[round]) ordered.push(bucket[round]);
    }
  }

  const half = Math.floor(CONTEXT_CHARS / 2);
  const ranges = ordered.map((hit) => ({
    start: Math.max(0, hit.index - half),
    end: Math.min(text.length, hit.index + hit.term.length + half),
    concepts: [hit.concept],
    terms: [hit.term],
  }));

  // Merge overlapping windows so a dense passage is not repeated, keeping the
  // union of what each contributed.
  ranges.sort((a, b) => a.start - b.start);
  const merged: typeof ranges = [ranges[0]];
  for (const range of ranges.slice(1)) {
    const last = merged[merged.length - 1];
    if (range.start <= last.end) {
      last.end = Math.max(last.end, range.end);
      for (const concept of range.concepts) {
        if (!last.concepts.includes(concept)) last.concepts.push(concept);
      }
      for (const term of range.terms) if (!last.terms.includes(term)) last.terms.push(term);
    } else {
      merged.push(range);
    }
  }

  const windows: EvidenceWindow[] = [];
  let used = 0;
  let truncated = false;

  for (const range of merged) {
    const slice = text.slice(range.start, range.end).trim();
    if (used + slice.length > MAX_EXCERPT_CHARS) {
      const remaining = MAX_EXCERPT_CHARS - used;
      if (remaining > 200) {
        windows.push({
          start: range.start,
          end: range.start + remaining,
          concepts: range.concepts,
          terms: range.terms,
          text: slice.slice(0, remaining),
        });
        used += remaining;
      }
      truncated = true;
      break;
    }
    windows.push({
      start: range.start,
      end: range.end,
      concepts: range.concepts,
      terms: range.terms,
      text: slice,
    });
    used += slice.length;
  }

  const matchedConcepts = [...new Set(windows.flatMap((window) => window.concepts))];
  const matchedTerms = [...new Set(windows.flatMap((window) => window.terms))];

  return {
    excerpt: windows.map((window) => window.text).join('\n…\n'),
    windows,
    concepts: matchedConcepts,
    matchedTerms,
    fullLength: text.length,
    truncated,
    fallback: false,
  };
}
